def strings(lang: str) -> dict[str, str]:
    """Полный словарь языка: английский как основа, поверх — перевод.

    Так новый ключ, забытый в переводе, показывается по-английски, а не пропадает.
    """
    out = dict(APP_STRINGS[FALLBACK])
    out.update(APP_STRINGS.get(lang, {}))
    return out
